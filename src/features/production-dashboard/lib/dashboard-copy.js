/**
 * Cache theo mã ngôn ngữ đã chuẩn hoá.
 *
 * Component gọi `getDashboardCopy(language)` ở mỗi lần render (đồng hồ đổi mỗi
 * giây), mà mỗi lần gọi đều `String().split('-')[0]` cấp phát chuỗi mới và tra
 * bảng. Chỉ có 3 ngôn ngữ và giá trị trả về là hằng số bất biến nên cache vô
 * hại, khỏi cần `useMemo` ở từng nơi dùng.
 */
const COPY_CACHE = new Map();

export function getDashboardCopy(language) {
  const languageCode = String(language || 'vi').split('-')[0];
  const cached = COPY_CACHE.get(languageCode);
  if (cached) return cached;

  const copy = DASHBOARD_COPY[languageCode] || DASHBOARD_COPY.vi;
  COPY_CACHE.set(languageCode, copy);
  return copy;
}
